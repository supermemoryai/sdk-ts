// Generates the public SDK surface — src/models/**, src/funcs/**, src/sdk/** —
// from fern/openapi.json + fern/overlay.yaml. HTTP goes through the
// Fern-generated client in src/generated (see src/lib/invoke.ts).
//
// Type names come from fern/surface-names.json (pinned to the names the
// 5.0.0-rc.5 SDK shipped) and fall back to a naming rule for anything newer,
// so spec changes never need edits here.
import { rmSync } from "node:fs";
import { join } from "node:path";
import { camel, loadSpec, type Operation, pascal, type Schema, type Spec, unwrapNullable, variantsOf } from "./spec.ts";

type Dir = "in" | "out";

type Decl = {
  name: string;
  ptr: string;
  /** Module path under src/, without extension. */
  module: string;
  kind: "object" | "enum" | "union" | "file" | "errorClass";
  schema: Schema;
  dirs: Set<Dir>;
  description?: string;
};

const STATUS_NAMES: Record<number, string> = {
  400: "BadRequest", 401: "Unauthorized", 402: "PaymentRequired", 403: "Forbidden", 404: "NotFound",
  405: "MethodNotAllowed", 409: "Conflict", 410: "Gone", 413: "PayloadTooLarge", 415: "UnsupportedMediaType",
  422: "UnprocessableEntity", 429: "TooManyRequests", 500: "InternalServerError", 501: "NotImplemented",
  502: "BadGateway", 503: "ServiceUnavailable", 504: "GatewayTimeout",
};

const HEADER = "/*\n * Generated by scripts/surface/generate.ts from fern/openapi.json. DO NOT EDIT.\n */\n";

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const enumKey = (v: string) => {
  const k = pascal(String(v));
  return /^[A-Za-z_]/.test(k) ? k : `Value${k}`;
};
const quoteKey = (k: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));
const doc = (text: string | undefined, indent = "") =>
  text ? `${indent}/**\n${text.split("\n").map((l) => `${indent} * ${l.replace(/\*\//g, "*\\/")}`.trimEnd()).join("\n")}\n${indent} */\n` : "";

export async function generateSurface(root: string) {
  const spec = await loadSpec(root);
  const pinned = (await Bun.file(join(root, "fern/surface-names.json")).json()) as { names: Record<string, string>; order: Record<string, number[]> };
  const pkg = await Bun.file(join(root, "package.json")).json();

  const decls = new Map<string, Decl>(); // by ptr
  const byName = new Map<string, Decl>();
  const R = spec.resolve;
  const P = spec.ptr;

  // ---------------------------------------------------------------- shapes
  const nonNull = (s: Schema) => unwrapNullable(spec, s);
  const literalValues = (s: Schema): unknown[] | undefined => {
    const r = R(s);
    if (r.const !== undefined) return [r.const];
    if (Array.isArray(r.enum)) return r.enum;
  };
  const isEnum = (s: Schema) => {
    const v = literalValues(s);
    return !!v && v.length > 1 && v.every((x) => typeof x === "string");
  };
  const isLiteral = (s: Schema) => literalValues(s)?.length === 1;
  const isObject = (s: Schema) => {
    const r = R(s);
    return !!r.properties && Object.keys(r.properties).length > 0;
  };
  const unionVariants = (s: Schema): Schema[] | undefined => {
    const v = variantsOf(spec, s);
    if (!v) return;
    const order = pinned.order[P(R(s))];
    return order ? order.map((i) => v[i]!) : v;
  };
  const isBinary = (s: Schema) => R(s).type === "string" && R(s).format === "binary";
  const isPrimitive = (s: Schema): boolean => {
    const r = R(nonNull(s).schema);
    if (unionVariants(r)) return unionVariants(r)!.every(isPrimitive);
    return ["string", "number", "integer", "boolean"].includes(r.type) || (r.type === "array" && !!r.items && isPrimitive(r.items));
  };
  const componentName = (s: Schema) => {
    const m = /^\/components\/schemas\/([^/]+)$/.exec(P(R(s)));
    return m?.[1];
  };

  // ------------------------------------------------------------ discovery
  const unique = (name: string, ptr: string) => {
    let candidate = name;
    for (let i = 2; byName.has(candidate) && byName.get(candidate)!.ptr !== ptr; i++) candidate = `${name}${i}`;
    return candidate;
  };

  const declareType = (s: Schema, kind: Decl["kind"], hint: string, module: string, dir: Dir): Decl => {
    const ptr = P(s);
    let d = decls.get(ptr);
    if (!d) {
      const name = unique(pinned.names[ptr] ?? hint, ptr);
      d = { name, ptr, module, kind, schema: s, dirs: new Set(), ...(R(s).description ? { description: R(s).description } : {}) };
      decls.set(ptr, d);
      byName.set(name, d);
    }
    if (!d.dirs.has(dir)) {
      d.dirs.add(dir);
      return { ...d, dirs: new Set(["__new__" as Dir]) }; // signal: descend
    }
    return d;
  };

  /** Registers every named type reachable from `schema`. */
  function discover(schema: Schema, hint: string, module: string, dir: Dir) {
    const { schema: inner } = nonNull(schema);
    const s = R(inner);
    const comp = componentName(inner);
    if (comp) {
      hint = pinned.names[P(s)] ?? pascal(comp);
      module = `models/${kebab(hint)}`;
    }
    if (isBinary(s)) {
      declareType(s, "file", `${hint}`, module, dir);
      return;
    }
    if (isEnum(s)) {
      declareType(s, "enum", hint, module, dir);
      return;
    }
    const variants = unionVariants(s);
    if (variants && variants.length > 1) {
      const d = declareType(s, "union", hint, module, dir);
      if (!d.dirs.has("__new__" as Dir)) return;
      variants.forEach((v, i) => discover(v, `${hint}${i + 1}`, module, dir));
      return;
    }
    if (variants && variants.length === 1) return discover(variants[0]!, hint, module, dir);
    if (s.type === "array" && s.items) return discover(s.items, hint, module, dir);
    if (isObject(s)) {
      const d = declareType(s, "object", hint, module, dir);
      if (!d.dirs.has("__new__" as Dir)) return;
      for (const [k, v] of Object.entries(s.properties as Record<string, Schema>)) discover(v, `${hint}${pascal(k)}`, module, dir);
      return;
    }
    if (s.additionalProperties && typeof s.additionalProperties === "object") discover(s.additionalProperties, hint, module, dir);
  }

  // Per-operation roots.
  type OpPlan = {
    op: Operation;
    module: string;
    funcName: string;
    funcFile: string;
    request?: { name: string; schema: Schema; wrapped: boolean };
    response?: { schema: Schema; isArray: boolean; text: Array<{ status: number; contentType: string }> };
    errors: Array<{ status: number; schema: Schema }>;
  };
  const plans: OpPlan[] = [];

  for (const op of spec.ops) {
    const module = `models/operations/${kebab(op.opId)}`;
    const funcName = op.group ? `${camel(op.group)}${pascal(op.name)}` : op.name;
    const plan: OpPlan = { op, module, funcName, funcFile: kebab(funcName), errors: [] };

    for (const p of op.params) discover(p.schema, `${op.pascal}${pascal(p.name)}`, module, "out");
    if (op.body) discover(op.body.schema, op.params.length ? `${op.pascal}RequestBody` : `${op.pascal}Request`, module, "out");
    if (op.params.length) {
      const props: Schema = {};
      const required: string[] = [];
      for (const p of op.params) {
        props[p.name] = p.schema;
        if (p.required) required.push(p.name);
      }
      if (op.body) {
        props.body = op.body.schema;
        if (op.body.required) required.push("body");
      }
      const schema = spec.synthetic(`op:${op.opId}:request`, { type: "object", properties: props, required });
      const d = declareType(schema, "object", `${op.pascal}Request`, module, "out");
      plan.request = { name: d.name, schema, wrapped: true };
    } else if (op.body) {
      plan.request = { name: decls.get(P(R(nonNull(op.body.schema).schema)))!.name, schema: op.body.schema, wrapped: false };
    }

    const bodies = op.success.filter((r) => r.contentType === "application/json" || r.contentType.startsWith("text/"));
    if (bodies.length) {
      const variants = bodies.map((r) => (r.contentType.startsWith("text/") ? spec.synthetic(`op:${op.opId}:response:${r.status}:text`, { type: "string" }) : r.schema));
      const distinct = [...new Map(variants.map((v) => [P(v), v])).values()];
      let schema: Schema = distinct.length === 1 ? distinct[0]! : spec.synthetic(`op:${op.opId}:response`, { oneOf: distinct });
      const isArray = R(schema).type === "array";
      if (distinct.length > 1) {
        // Name the variants like rc.5: <Op>ResponseBody, <Op>ResponseBody2, …
        declareType(schema, "union", `${op.pascal}Response`, module, "in");
        distinct.forEach((v, i) => discover(v, `${op.pascal}ResponseBody${i ? i + 1 : ""}`, module, "in"));
      } else {
        discover(isArray ? R(schema).items : schema, `${op.pascal}Response`, module, "in");
      }
      plan.response = { schema, isArray, text: bodies.filter((r) => r.contentType.startsWith("text/")).map((r) => ({ status: r.status, contentType: r.contentType })) };
    }

    for (const e of op.errors) {
      const s = R(e.schema);
      const comp = componentName(e.schema);
      if (comp) {
        declareErrorClass(e.schema);
      } else if (unionVariants(s)) {
        const d = declareType(s, "union", `${op.pascal}${STATUS_NAMES[e.status] ?? `Status${e.status}`}`, `models/errors/${kebab(op.opId)}`, "in");
        if (d.dirs.has("__new__" as Dir)) for (const v of unionVariants(s)!) componentName(v) ? declareErrorClass(v) : discover(v, d.name, d.module, "in");
      } else if (isObject(s)) {
        declareErrorClass(e.schema, `${op.pascal}${STATUS_NAMES[e.status] ?? `Status${e.status}`}`);
      }
      plan.errors.push(e);
    }
    plans.push(plan);
  }

  function declareErrorClass(schema: Schema, fallback?: string) {
    const s = R(schema);
    const name = pinned.names[P(s)] ?? (componentName(schema) ? pascal(componentName(schema)!) : fallback!);
    const d = declareType(s, "errorClass", name, `models/errors/${kebab(name)}`, "in");
    if (!d.dirs.has("__new__" as Dir)) return;
    for (const [k, v] of Object.entries((s.properties ?? {}) as Record<string, Schema>)) discover(v, `${name}${pascal(k)}`, `models/${kebab(name)}`, "in");
  }

  // ------------------------------------------------------------- emission
  type Mod = { imports: Map<string, Set<string>>; body: string[]; exportsTypes: Set<string> };
  const modules = new Map<string, Mod>();
  const mod = (m: string) => {
    let x = modules.get(m);
    if (!x) modules.set(m, (x = { imports: new Map(), body: [], exportsTypes: new Set() }));
    return x;
  };
  const relImport = (from: string, to: string) => {
    const a = from.split("/").slice(0, -1);
    const b = to.split("/");
    let i = 0;
    while (i < a.length && a[i] === b[i]) i++;
    const up = a.length - i;
    return `${up ? "../".repeat(up) : "./"}${b.slice(i).join("/")}.js`;
  };
  const use = (m: string, target: string, name: string) => {
    if (target === m) return name;
    const path = relImport(m, target);
    let set = mod(m).imports.get(path);
    if (!set) mod(m).imports.set(path, (set = new Set()));
    set.add(name);
    return name;
  };
  const rt = (m: string, path: string, name: string) => use(m, path, name);

  const declOf = (s: Schema) => decls.get(P(R(nonNull(s).schema)));

  /** TS type for a schema, from module `m`. */
  function typeOf(schema: Schema, m: string, dir: Dir): string {
    const { schema: inner, nullable } = nonNull(schema);
    const t = baseType(inner, m, dir);
    return nullable ? `${t} | null` : t;
  }
  function baseType(schema: Schema, m: string, dir: Dir): string {
    const s = R(schema);
    const d = decls.get(P(s));
    if (d && d.kind === "file") return `${use(m, d.module, d.name)} | Blob`;
    if (d && d.kind === "errorClass") return use(m, d.module, d.name);
    if (d && d.kind !== "union") return use(m, d.module, d.name);
    if (d && d.kind === "union" && !isPrimitive(s)) return use(m, d.module, d.name);
    const lit = literalValues(s);
    if (lit?.length === 1) return JSON.stringify(lit[0]);
    const v = unionVariants(s);
    if (v && v.length > 1) return v.map((x) => wrapUnion(typeOf(x, m, dir))).join(" | ");
    if (v && v.length === 1) return typeOf(v[0]!, m, dir);
    switch (s.type) {
      case "string":
        return s.format === "date-time" ? "Date" : "string";
      case "number":
      case "integer":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `Array<${s.items ? typeOf(s.items, m, dir) : "any"}>`;
    }
    if (s.additionalProperties && typeof s.additionalProperties === "object" && Object.keys(s.additionalProperties).length) {
      return `{ [k: string]: ${typeOf(s.additionalProperties, m, dir)} }`;
    }
    if (s.type === "object" || s.additionalProperties || s.propertyNames) return "{ [k: string]: any }";
    return "any";
  }
  const wrapUnion = (t: string) => (t.includes("=>") ? `(${t})` : t);

  // rc.5 applies only scalar defaults (not object/array ones).
  const hasDefault = (s: Schema) => {
    const d = R(s).default !== undefined ? R(s).default : R(nonNull(s).schema).default;
    return d !== undefined && (d === null || typeof d !== "object");
  };
  const defaultOf = (s: Schema) => (R(s).default !== undefined ? R(s).default : R(nonNull(s).schema).default);

  /** zod expression for a schema in direction `dir`. */
  function zodOf(schema: Schema, m: string, dir: Dir, opts: { optional?: boolean } = {}): string {
    const { schema: inner, nullable } = nonNull(schema);
    let z = zodBase(inner, m, dir);
    if (dir === "in") {
      // rc.5: an optional response field with a default is filled in, so it is required in the type.
      if (opts.optional && hasDefault(schema)) return `z._default(${nullable ? `z.nullable(${z})` : z}, ${JSON.stringify(defaultOf(schema))})`;
      if (opts.optional && nullable) return `z.optional(z.nullable(${z}))`;
      if (opts.optional) return `types.optional(${z})`;
      if (nullable) return `types.nullable(${z})`;
      return z;
    }
    if (nullable) z = `z.nullable(${z})`;
    if (opts.optional && hasDefault(schema)) return `z._default(${z}, ${JSON.stringify(defaultOf(schema))})`;
    if (opts.optional) return `z.optional(${z})`;
    return z;
  }
  function zodBase(schema: Schema, m: string, dir: Dir): string {
    const s = R(schema);
    const d = decls.get(P(s));
    const suffix = dir === "in" ? "$inboundSchema" : "$outboundSchema";
    if (d && d.kind === "file") return `z.union([z.lazy(() => ${use(m, d.module, d.name + suffix)}), ${rt(m, "types/blobs", "blobLikeSchema")}])`;
    if (d && d.kind === "enum") return use(m, d.module, d.name + suffix);
    if (d && d.kind === "union" && !isPrimitive(s)) return d.module === m ? `z.lazy(() => ${d.name + suffix})` : use(m, d.module, d.name + suffix);
    if (d && (d.kind === "object" || d.kind === "errorClass")) return `z.lazy(() => ${use(m, d.module, d.name + suffix)})`;
    const lit = literalValues(s);
    if (lit?.length === 1) return dir === "in" ? `types.literal(${JSON.stringify(lit[0])})` : `z.literal(${JSON.stringify(lit[0])})`;
    const v = unionVariants(s);
    if (v && v.length > 1) {
      rt(m, "types/smart-union", "smartUnion");
      return `smartUnion([${v.map((x) => zodOf(x, m, dir)).join(", ")}])`;
    }
    if (v && v.length === 1) return zodOf(v[0]!, m, dir);
    if (dir === "in") {
      switch (s.type) {
        case "string":
          return s.format === "date-time" ? "types.date()" : "types.string()";
        case "number":
        case "integer":
          return "types.number()";
        case "boolean":
          return "types.boolean()";
        case "null":
          return "z.null()";
        case "array":
          return `z.array(${s.items ? zodOf(s.items, m, dir) : "z.any()"})`;
      }
    } else {
      switch (s.type) {
        case "string":
          return s.format === "date-time" ? "z.pipe(z.date(), z.transform(v => v.toISOString()))" : "z.string()";
        case "number":
          return "z.number()";
        case "integer":
          return "z.int()";
        case "boolean":
          return "z.boolean()";
        case "null":
          return "z.null()";
        case "array":
          return `z.array(${s.items ? zodOf(s.items, m, dir) : "z.any()"})`;
      }
    }
    if (s.additionalProperties && typeof s.additionalProperties === "object" && Object.keys(s.additionalProperties).length) {
      return `z.record(z.string(), ${zodOf(s.additionalProperties, m, dir)})`;
    }
    if (s.type === "object" || s.additionalProperties || s.propertyNames) return "z.record(z.string(), z.any())";
    return "z.any()";
  }

  /** `$Outbound` wire type (dates become strings). */
  function outboundTypeOf(schema: Schema, m: string): string {
    const { schema: inner, nullable } = nonNull(schema);
    const s = R(inner);
    const d = decls.get(P(s));
    let t: string;
    if (d && d.kind === "file") t = `${use(m, d.module, d.name + "$Outbound")} | Blob`;
    else if (d && d.kind === "enum") t = "string";
    else if (d && (d.kind === "object" || (d.kind === "union" && !isPrimitive(s)))) t = use(m, d.module, d.name + "$Outbound");
    else {
      const v = unionVariants(s);
      const lit = literalValues(s);
      if (lit?.length === 1) t = JSON.stringify(lit[0]);
      else if (v && v.length > 1) t = v.map((x) => outboundTypeOf(x, m)).join(" | ");
      else if (s.type === "array") t = `Array<${s.items ? outboundTypeOf(s.items, m) : "any"}>`;
      else if (s.type === "string" && s.format === "date-time") t = "string";
      else t = baseType(inner, m, "out");
    }
    return nullable ? `${t} | null` : t;
  }

  const fromJSON = (name: string, m: string) => {
    rt(m, "lib/schemas", "safeParse");
    use(m, "types/fp", "Result as SafeParseResult");
    use(m, "models/errors/sdk-validation-error", "SDKValidationError");
    return `export function ${lowerFirst(name)}FromJSON(\n  jsonString: string,\n): SafeParseResult<${name}, SDKValidationError> {\n  return safeParse(\n    jsonString,\n    (x) => ${name}$inboundSchema.parse(JSON.parse(x)),\n    \`Failed to parse '${name}' from JSON\`,\n  );\n}\n`;
  };
  const toJSON = (name: string) =>
    `export function ${lowerFirst(name)}ToJSON(\n  ${lowerFirst(name)}: ${name},\n): string {\n  return JSON.stringify(${name}$outboundSchema.parse(${lowerFirst(name)}));\n}\n`;

  const objectFields = (d: Decl, m: string, dir: Dir, kind: "type" | "outbound" | "zod") => {
    const s = R(d.schema);
    const required = new Set<string>(s.required ?? []);
    return Object.entries(s.properties as Record<string, Schema>)
      .map(([k, v]) => {
        const opt = dir === "out" ? !required.has(k) || hasDefault(v) : !required.has(k) && !hasDefault(v);
        if (kind === "zod") return `  ${quoteKey(k)}: ${zodOf(v, m, dir, { optional: !required.has(k) })},\n`;
        const t = kind === "outbound" ? outboundTypeOf(v, m) : typeOf(v, m, dir);
        const desc = R(nonNull(v).schema).description ?? R(v).description;
        return `${doc(desc, "  ")}  ${quoteKey(k)}${opt ? "?" : ""}: ${t}${opt ? " | undefined" : ""};\n`;
      })
      .join("");
  };

  // Enums and file types are referenced directly (not lazily), so they come first.
  const priority = (d: Decl) => (d.kind === "enum" ? 0 : d.kind === "file" ? 1 : 2);
  for (const d of [...decls.values()].sort((a, b) => priority(a) - priority(b))) {
    const m = d.module;
    const out = mod(m).body;
    const s = R(d.schema);
    mod(m).exportsTypes.add(d.name);
    if (d.kind === "enum") {
      const values = literalValues(s) as string[];
      const open = d.dirs.has("in");
      const helper = open ? "OpenEnum" : "ClosedEnum";
      use(m, "types/enums", helper);
      out.push(`${doc(d.description)}export const ${d.name} = {\n${values.map((v) => `  ${enumKey(v)}: ${JSON.stringify(v)},\n`).join("")}} as const;\n${doc(d.description)}export type ${d.name} = ${helper}<typeof ${d.name}>;\n`);
      if (d.dirs.has("in")) {
        use(m, "types/enums", "* as openEnums");
        out.push(`/** @internal */\nexport const ${d.name}$inboundSchema: z.ZodMiniType<${d.name}, unknown> = openEnums.inboundSchema(${d.name});\n`);
      }
      if (d.dirs.has("out")) out.push(`/** @internal */\nexport const ${d.name}$outboundSchema: z.ZodMiniEnum<typeof ${d.name}> = z.enum(${d.name});\n`);
      continue;
    }
    if (d.kind === "file") {
      out.push(`export type ${d.name} = {\n  fileName: string;\n  content: ReadableStream<Uint8Array> | Blob | ArrayBuffer | Uint8Array;\n};\n`);
      out.push(`/** @internal */\nexport type ${d.name}$Outbound = {\n  fileName: string;\n  content: ReadableStream<Uint8Array> | Blob | ArrayBuffer | Uint8Array;\n};\n`);
      out.push(`/** @internal */\nexport const ${d.name}$outboundSchema: z.ZodMiniType<${d.name}$Outbound, ${d.name}> = z.object({\n  fileName: z.string(),\n  content: z.union([\n    z.custom<ReadableStream<Uint8Array>>(x => x instanceof ReadableStream),\n    z.custom<Blob>(x => x instanceof Blob),\n    z.custom<ArrayBuffer>(x => x instanceof ArrayBuffer),\n    z.custom<Uint8Array>(x => x instanceof Uint8Array),\n  ]),\n});\n`);
      out.push(toJSON(d.name));
      continue;
    }
    if (d.kind === "union") {
      const variants = unionVariants(s)!;
      const dir: Dir = d.dirs.has("in") ? "in" : "out";
      out.push(`${doc(d.description)}export type ${d.name} =\n${variants.map((v) => `  | ${typeOf(v, m, dir)}\n`).join("")};\n`);
      if (d.dirs.has("in")) {
        rt(m, "types/smart-union", "smartUnion");
        out.push(`/** @internal */\nexport const ${d.name}$inboundSchema: z.ZodMiniType<${d.name}, unknown> = smartUnion([\n${variants.map((v) => `  ${zodOf(v, m, "in")},\n`).join("")}]);\n`);
        out.push(fromJSON(d.name, m));
      }
      if (d.dirs.has("out")) {
        rt(m, "types/smart-union", "smartUnion");
        out.push(`/** @internal */\nexport type ${d.name}$Outbound =\n${variants.map((v) => `  | ${outboundTypeOf(v, m)}\n`).join("")};\n`);
        out.push(`/** @internal */\nexport const ${d.name}$outboundSchema: z.ZodMiniType<${d.name}$Outbound, ${d.name}> = smartUnion([\n${variants.map((v) => `  ${zodOf(v, m, "out")},\n`).join("")}]);\n`);
        out.push(toJSON(d.name));
      }
      continue;
    }
    if (d.kind === "errorClass") {
      use(m, "models/errors/supermemory-error", "SupermemoryError");
      const fields = Object.entries((s.properties ?? {}) as Record<string, Schema>);
      const required = new Set<string>(s.required ?? []);
      out.push(`${doc(d.description)}export type ${d.name}Data = {\n${objectFields(d, m, "in", "type")}};\n`);
      out.push(`${doc(d.description)}export class ${d.name} extends SupermemoryError {\n${fields.map(([k, v]) => `${doc(R(v).description, "  ")}  ${quoteKey(k)}${required.has(k) ? "" : "?"}: ${typeOf(v, m, "in")}${required.has(k) ? "" : " | undefined"};\n`).join("")}\n  /** The original data that was passed to this error instance. */\n  data$: ${d.name}Data;\n\n  constructor(\n    err: ${d.name}Data,\n    httpMeta: { response: Response; request: Request; body: string },\n  ) {\n    const message = "message" in err && typeof err.message === "string"\n      ? err.message\n      : \`API error occurred: \${JSON.stringify(err)}\`;\n    super(message, httpMeta);\n    this.data$ = err;\n${fields.map(([k]) => (required.has(k) ? `    this.${k} = err.${k};\n` : `    if (err.${k} != null) this.${k} = err.${k};\n`)).join("")}\n    this.name = ${JSON.stringify(d.name)};\n  }\n}\n`);
      out.push(`/** @internal */\nexport const ${d.name}$inboundSchema: z.ZodMiniType<${d.name}, unknown> = z.pipe(\n  z.object({\n${objectFields(d, m, "in", "zod").replace(/^/gm, "  ").replace(/^  $/gm, "")}    request$: z.custom<Request>(x => x instanceof Request),\n    response$: z.custom<Response>(x => x instanceof Response),\n    body$: z.string(),\n  }),\n  z.transform((v) => {\n    return new ${d.name}(v, {\n      request: v.request$,\n      response: v.response$,\n      body: v.body$,\n    });\n  }),\n);\n`);
      continue;
    }
    // object
    out.push(`${doc(d.description)}export type ${d.name} = {\n${objectFields(d, m, d.dirs.has("out") && !d.dirs.has("in") ? "out" : "in", "type")}};\n`);
    if (d.dirs.has("in")) {
      out.push(`/** @internal */\nexport const ${d.name}$inboundSchema: z.ZodMiniType<${d.name}, unknown> = z.object({\n${objectFields(d, m, "in", "zod")}});\n`);
      out.push(fromJSON(d.name, m));
    }
    if (d.dirs.has("out")) {
      out.push(`/** @internal */\nexport type ${d.name}$Outbound = {\n${objectFields(d, m, "out", "outbound")}};\n`);
      out.push(`/** @internal */\nexport const ${d.name}$outboundSchema: z.ZodMiniType<${d.name}$Outbound, ${d.name}> = z.object({\n${objectFields(d, m, "out", "zod")}});\n`);
      out.push(toJSON(d.name));
    }
  }

  // ----------------------------------------------------------------- funcs
  const dir = (p: string) => join(root, "src", p);
  // Remove previously generated files (identified by HEADER); hand-maintained
  // runtime files such as models/errors/supermemory-error.ts stay.
  for (const f of new Bun.Glob("{models,funcs,sdk,lib}/**/*.ts").scanSync({ cwd: join(root, "src") })) {
    if ((await Bun.file(dir(f)).text()).startsWith(HEADER)) rmSync(dir(f));
  }

  const funcs: string[] = [];
  const responseTypeOf = (plan: OpPlan, m: string): string => {
    const r = plan.response;
    if (!r) return "void";
    if (r.isArray) return `Array<${typeOf(R(r.schema).items, m, "in")}>`;
    return typeOf(r.schema, m, "in");
  };
  const responseSchemaOf = (plan: OpPlan, m: string): string => {
    const r = plan.response!;
    if (r.isArray) return `z.array(${zodOf(R(r.schema).items, m, "in")})`;
    const d = decls.get(P(R(r.schema)));
    if (d && d.kind === "union") return use(m, d.module, d.name + "$inboundSchema");
    return zodOf(r.schema, m, "in");
  };

  for (const plan of plans) {
    const { op } = plan;
    const m = `funcs/${plan.funcFile}`;
    const out = mod(m).body;
    use(m, "core", "SupermemoryCore");
    use(m, "lib/sdks", "RequestOptions");
    use(m, "lib/invoke", "invoke");
    use(m, "lib/invoke", "OperationSpec");
    use(m, "types/async", "APIPromise");
    use(m, "types/fp", "Result");
    for (const e of ["ConnectionError", "InvalidRequestError", "RequestAbortedError", "RequestTimeoutError", "UnexpectedClientError"]) use(m, "models/errors/http-client-errors", e);
    use(m, "models/errors/response-validation-error", "ResponseValidationError");
    use(m, "models/errors/sdk-validation-error", "SDKValidationError");
    use(m, "models/errors/supermemory-error", "SupermemoryError");
    use(m, "lib/matchers", "* as M");

    const respType = responseTypeOf(plan, m);
    const errTypes = new Set<string>();
    const errMatchers: string[] = [];
    // Group consecutive statuses that share an error type, like rc.5 did.
    const groups: Array<{ codes: number[]; schema: string; type: string }> = [];
    for (const e of plan.errors) {
      const s = R(e.schema);
      const d = decls.get(P(s));
      const type = d ? use(m, d.module, d.name) : "unknown";
      const schema = d ? use(m, d.module, `${d.name}$inboundSchema`) : "z.unknown()";
      errTypes.add(type);
      const last = groups.at(-1);
      if (last && last.type === type && String(last.codes.at(-1)).charAt(0) === String(e.status).charAt(0) && e.status !== 400 && last.codes[0] !== 400) last.codes.push(e.status);
      else groups.push({ codes: [e.status], schema, type });
    }
    for (const g of groups) errMatchers.push(`M.jsonErr(${g.codes.length === 1 ? g.codes[0] : `[${g.codes.join(", ")}]`}, ${g.schema})`);
    errMatchers.push(`M.fail("4XX")`, `M.fail("5XX")`);

    const successMatchers: string[] = [];
    if (plan.response) {
      const schemaExpr = responseSchemaOf(plan, m);
      for (const r of op.success) {
        if (r.contentType === "application/json") successMatchers.push(`M.json(${r.status}, ${schemaExpr})`);
        else if (r.contentType.startsWith("text/")) successMatchers.push(`M.text(${r.status}, ${schemaExpr}, { ctype: ${JSON.stringify(r.contentType)} })`);
      }
    } else {
      for (const r of op.success) successMatchers.push(`M.nil(${r.status}, z.void())`);
      if (!op.success.length) successMatchers.push(`M.nil("2XX", z.void())`);
    }

    const errorUnion = [...errTypes, "SupermemoryError", "ResponseValidationError", "ConnectionError", "RequestAbortedError", "RequestTimeoutError", "InvalidRequestError", "UnexpectedClientError", "SDKValidationError"];
    const resultType = `Result<\n    ${respType},\n${errorUnion.map((t) => `    | ${t}\n`).join("")}  >`;

    const accept = (() => {
      const types = [...new Set(op.success.map((r) => r.contentType))];
      if (types.length <= 1) return types[0] ?? "application/json";
      return types.map((t, i) => `${t};q=${i === 0 ? 1 : Math.max(0, 1 - i).toString()}`).join(", ");
    })();

    const req = plan.request;
    const reqOpt = !!req && !(R(nonNull(req.schema).schema).required ?? []).length;
    let reqSchema = "undefined";
    let reqType = "";
    if (req) {
      const d = decls.get(P(R(nonNull(req.schema).schema)))!;
      reqType = use(m, d.module, d.name);
      reqSchema = use(m, d.module, `${d.name}$outboundSchema`);
    }

    const fields = (s: Schema) => Object.keys((R(nonNull(s).schema).properties ?? {}) as object);
    const bodySchema = op.body ? R(nonNull(op.body.schema).schema) : undefined;
    const bodyFields = bodySchema ? fields(bodySchema) : [];
    const collisions = bodyFields.filter((f) => op.params.some((p) => p.name === f));
    if (collisions.length) throw new Error(`${op.opId}: body fields ${collisions.join(", ")} collide with parameters; Fern would rename them`);

    const specObj = {
      operationID: op.opId,
      method: op.method,
      path: op.path,
      fern: [op.group, op.name].filter(Boolean),
      params: op.params.map((p) => ({ name: p.name, in: p.in })),
      body: op.body
        ? {
            key: req?.wrapped ? "body" : null,
            contentType: op.body.contentType,
            // Fern inlines object bodies into the request; anything else stays under `body`.
            fernWrapped: !bodySchema || !isObject(bodySchema),
            ...(op.body.contentType === "multipart/form-data"
              ? { fileFields: bodyFields.filter((f) => isBinary(bodySchema!.properties[f])) }
              : {}),
          }
        : null,
      accept,
    };

    use(m, "lib/invoke", "OperationSpec");
    mod(m).imports.set("zod/v4-mini", new Set(["* as z"]));
    out.push(`const spec: OperationSpec = ${JSON.stringify(specObj, null, 2).replace(/"([A-Za-z]+)":/g, "$1:")};\n`);
    const desc = [op.description].filter(Boolean).join("\n");
    out.push(
      `${doc(desc)}export function ${plan.funcName}(\n  client: SupermemoryCore,\n${req ? `  request${reqOpt ? "?" : ""}: ${reqType},\n` : ""}  options?: RequestOptions,\n): APIPromise<\n  ${resultType}\n> {\n  return invoke(client, spec, ${req ? (reqOpt ? "request ?? {}" : "request") : "undefined"}, ${reqSchema}, options, [\n${[...successMatchers, ...errMatchers].map((x) => `    ${x},\n`).join("")}  ]);\n}\n`,
    );
    funcs.push(plan.funcFile);
  }

  // ------------------------------------------------------------------ sdk
  const groups = new Map<string | null, OpPlan[]>();
  for (const plan of plans) {
    const g = plan.op.group;
    groups.set(g, [...(groups.get(g) ?? []), plan]);
  }
  const method = (plan: OpPlan, m: string) => {
    const req = plan.request;
    const reqOpt = !!req && !(R(nonNull(req.schema).schema).required ?? []).length;
    use(m, `funcs/${plan.funcFile}`, plan.funcName);
    use(m, "types/fp", "unwrapAsync");
    use(m, "lib/sdks", "RequestOptions");
    const respType = responseTypeOf(plan, m);
    let reqType = "";
    if (req) {
      const d = decls.get(P(R(nonNull(req.schema).schema)))!;
      reqType = use(m, d.module, d.name);
    }
    return `${doc(plan.op.description, "  ")}  async ${plan.op.name}(\n${req ? `    request${reqOpt ? "?" : ""}: ${reqType},\n` : ""}    options?: RequestOptions,\n  ): Promise<${respType}> {\n    return unwrapAsync(${plan.funcName}(\n      this,\n${req ? "      request,\n" : ""}      options,\n    ));\n  }\n`;
  };
  const subgroups = [...groups.keys()].filter((g): g is string => g !== null);
  for (const g of subgroups) {
    const m = `sdk/${kebab(g)}`;
    use(m, "lib/sdks", "ClientSDK");
    mod(m).body.push(`export class ${pascal(g)} extends ClientSDK {\n${groups.get(g)!.map((p) => method(p, m)).join("\n")}}\n`);
  }
  {
    const m = "sdk/sdk";
    use(m, "lib/sdks", "ClientSDK");
    const getters = subgroups.map((g) => {
      use(m, `sdk/${kebab(g)}`, pascal(g));
      return `  private _${camel(g)}?: ${pascal(g)};\n  get ${camel(g)}(): ${pascal(g)} {\n    return (this._${camel(g)} ??= new ${pascal(g)}(this._options));\n  }\n`;
    });
    mod(m).body.push(`export class Supermemory extends ClientSDK {\n${getters.join("\n")}\n${(groups.get(null) ?? []).map((p) => method(p, m)).join("\n")}}\n`);
    mod("sdk/index").body.push(`export * from "./sdk.js";\n`);
  }

  // --------------------------------------------------------------- indexes
  const indexOf = (prefix: string) =>
    [...modules.keys()]
      .filter((k) => k.startsWith(prefix) && !k.slice(prefix.length).includes("/") && !k.endsWith("/index"))
      .sort()
      .map((k) => `export * from "./${k.slice(prefix.length)}.js";\n`)
      .join("");
  const errorRuntime = ["http-client-errors", "response-validation-error", "sdk-validation-error", "supermemory-default-error", "supermemory-error"];
  mod("models/operations/index").body.push(indexOf("models/operations/"));
  mod("models/errors/index").body.push(
    [...[...modules.keys()].filter((k) => k.startsWith("models/errors/") && !k.endsWith("/index")).map((k) => k.slice("models/errors/".length)), ...errorRuntime]
      .sort()
      .map((f) => `export * from "./${f}.js";\n`)
      .join(""),
  );
  mod("models/security").body.push(
    `export type Security = {\n  apiKey?: string | undefined;\n};\n\n/** @internal */\nexport type Security$Outbound = {\n  apiKey?: string | undefined;\n};\n\n/** @internal */\nexport const Security$outboundSchema: z.ZodMiniType<Security$Outbound, Security> = z.object({\n  apiKey: z.optional(z.string()),\n});\n\nexport function securityToJSON(security: Security): string {\n  return JSON.stringify(Security$outboundSchema.parse(security));\n}\n`,
  );
  mod("models/index").body.push(indexOf("models/"));
  mod("lib/surface").body.push(
    `export const ServerList = ${JSON.stringify(spec.servers)} as const;\n\nexport const SDK_VERSION = ${JSON.stringify(pkg.version)};\n\nexport const OPENAPI_DOC_VERSION = ${JSON.stringify(spec.doc.info?.version ?? "")};\n`,
  );

  // ----------------------------------------------------------------- write
  for (const [m, x] of modules) {
    const usesZod = x.body.some((b) => /\bz\./.test(b));
    const imports = [...x.imports.entries()]
      .filter(([path]) => path !== "zod/v4-mini")
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([path, names]) => {
        const star = [...names].find((n) => n.startsWith("* as "));
        const named = [...names].filter((n) => !n.startsWith("* as ")).sort();
        return [star ? `import ${star} from "${path}";\n` : "", named.length ? `import { ${named.join(", ")} } from "${path}";\n` : ""].join("");
      })
      .join("");
    const needsTypes = x.body.some((b) => /\btypes\.(string|number|boolean|date|literal|optional|nullable)\(/.test(b));
    const typesImport = needsTypes && !x.imports.has(relImport(m, "types/primitives")) ? `import * as types from "${relImport(m, "types/primitives")}";\n` : "";
    const src = `${HEADER}\n${usesZod || x.imports.has("zod/v4-mini") ? 'import * as z from "zod/v4-mini";\n' : ""}${imports.replace(/import \{ types \} from "[^"]+";\n/, "")}${typesImport}\n${x.body.join("\n")}`;
    await Bun.write(dir(`${m}.ts`), src);
  }

  return { ops: plans.length, types: decls.size };
}

if (import.meta.main) {
  const root = new URL("../..", import.meta.url).pathname;
  const { ops, types } = await generateSurface(root);
  console.log(`==> Surface: ${ops} operations, ${types} named types`);
}
